"""Aggregate evolution results into REPORT.md, a JSON summary, and figures.

Primary outcome: held-out test target accuracy minus the original model's.
Uncertainty: hierarchical bootstrap, resampling lineages within each arm and,
jointly for all arms, test items (paired by item).
"""
import json
from pathlib import Path

import numpy as np

R = Path("results/evolution")
RUNS = R / "runs"
FIG = R / "figures"
COLORS = {"E-LLM": "#2a78d6", "R-LLM": "#eb6834", "E-LLM-nohist": "#1baf7a", "E-LLM-free": "#eda100",
          "E-RAND": "#e87ba4", "ES-56": "#008300", "ES-56+": "#008300"}
ARMS = ["E-LLM", "R-LLM", "E-LLM-nohist", "E-LLM-free", "E-RAND", "ES-56", "ES-56+"]


def load_logs(arm):
    out = {}
    for d in sorted((RUNS / arm).glob("*/log.json")) if (RUNS / arm).exists() else []:
        out[d.parent.name] = json.loads(d.read_text())
    return out


def final_test(arm, log, gen="10"):
    t = log["tests"]
    if arm == "R-LLM":
        return t.get("final")
    return t.get(gen)


def original_test():
    for log in load_logs("E-LLM").values():
        if "0" in log["tests"]:
            return log["tests"]["0"]
    return None


ES_FROZEN_SEEDS = (1, 2)   # frozen protocol; seeds >= 3 are a documented addition


def es_logs(all_seeds=False):
    out = []
    for d in sorted((R / "es").glob("ES-56_seed*/log.json")):
        seed = int(d.parent.name.split("seed")[1])
        if all_seeds or seed in ES_FROZEN_SEEDS:
            out.append((d.parent.name, json.loads(d.read_text())))
    return out


def unit_tests(arm):
    """Final held-out test record per unit of an arm (ES-56+: all seeds)."""
    if arm == "ES-56+" and len(es_logs(True)) <= len(es_logs(False)):
        return []          # no additional seeds yet
    if arm.startswith("ES-56"):
        return [(n, l["tests"]["60"]) for n, l in es_logs(arm == "ES-56+") if "60" in l.get("tests", {})]
    return [(n, final_test(arm, l)) for n, l in load_logs(arm).items() if final_test(arm, l)]


def passes(t, orig, tol=0.02):
    return t["protected_fitness"] >= orig["protected_fitness"] - tol and t["nll"] <= orig["nll"] + tol


def item_vectors(arm, gen="10"):
    """Matrix lineages x items of test target correctness (1/0) for an arm."""
    rows, names = [], []
    if arm.startswith("ES-56"):
        for name, t in unit_tests(arm):
            rows.append(np.array(t["item_correct_target"], float)); names.append(name)
        return names, np.array(rows)
    for name, log in load_logs(arm).items():
        t = final_test(arm, log, gen)
        if t:
            rows.append(np.array(t["item_correct_target"], float)); names.append(name)
    return names, np.array(rows)


def boot_diff(A, B, base, n=10000, seed=0):
    """Mean over lineages of accuracy; returns (diff, lo, hi) for A - B (B may be None -> vs base)."""
    rng = np.random.default_rng(seed)
    n_items = A.shape[1]
    stats = []
    for _ in range(n):
        items = rng.integers(0, n_items, n_items)
        a = A[rng.integers(0, len(A), len(A))][:, items].mean()
        b = B[rng.integers(0, len(B), len(B))][:, items].mean() if B is not None else base[items].mean()
        stats.append(a - b)
    pt = A.mean() - (B.mean() if B is not None else base.mean())
    lo, hi = np.percentile(stats, [2.5, 97.5])
    return float(pt), float(lo), float(hi)


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    orig = original_test()
    summary = dict(original=None if orig is None else {k: orig[k] for k in ("target_acc", "protected_acc", "nll", "tasks")})
    base = np.array(orig["item_correct_target"], float) if orig else None
    lines = ["# Model evolution by WSP: results", "",
             "Generated by `python -m experiments.evolution.analyze`. All numbers trace to `results/evolution/`.", ""]
    if orig:
        lines += [f"Original model test target accuracy: **{orig['target_acc']:.4f}**; protected accuracy {orig['protected_acc']:.4f}; "
                  f"WikiText test NLL {orig['nll']:.4f}.", ""]
    # ---- per-arm table
    lines += ["## Per-arm final held-out results (generation 10; R-LLM: best-of; ES-56: best within 60 evaluations)", "",
              "ES-56 = frozen seeds 1-2; ES-56+ = all seeds (seeds >= 3 are an addition beyond the frozen protocol). "
              "'Pass' = test protected fitness >= original - 0.02 and test NLL <= original + 0.02 (the dev admissibility rule applied to test).", "",
              "| Arm | Units | Test target acc (mean; per-unit) | Δ vs original [95% CI] | Protected acc | Test NLL | Pass test constraints |",
              "|---|---|---|---|---|---|---|"]
    mats, pass_mats = {}, {}
    for arm in ARMS:
        units = unit_tests(arm)
        if not units:
            continue
        names, M = item_vectors(arm)
        mats[arm] = M
        tests = [t for _, t in units]
        ok = [passes(t, orig) for t in tests] if orig else [True] * len(tests)
        if any(ok):
            pass_mats[arm] = M[np.array(ok)]
        per = ", ".join(f"{t['target_acc']:.3f}" + ("" if k else "*") for t, k in zip(tests, ok))
        d = boot_diff(M, None, base) if base is not None else (float("nan"),) * 3
        pa = np.mean([t["protected_acc"] for t in tests]); nll = np.mean([t["nll"] for t in tests])
        lines.append(f"| {arm} | {len(names)} | {M.mean():.4f} ({per}) | {d[0]:+.4f} [{d[1]:+.4f}, {d[2]:+.4f}] | {pa:.4f} | {nll:.4f} | {sum(ok)}/{len(ok)} |")
        summary[arm] = dict(n=len(names), mean_acc=float(M.mean()), delta_vs_original=d, protected_acc=float(pa), nll=float(nll),
                            per_lineage=[t["target_acc"] for t in tests], n_pass_test_constraints=int(sum(ok)))
    lines += ["", "(*) = fails the test constraints.", ""]
    # ---- contrasts
    lines += ["## Contrasts (hierarchical bootstrap over lineages and paired test items)", "", "| Contrast | Δ acc | 95% CI |", "|---|---|---|"]
    for a, b, tag in [("E-LLM", "R-LLM", "C1 heredity"), ("E-LLM", "E-RAND", "C2 LLM content vs magnitude-matched random"),
                      ("E-LLM", "ES-56", "C3 vs CMA-ES (60 evals)"), ("E-LLM", "E-LLM-nohist", "C4 lineage memory"),
                      ("E-LLM-nohist", "R-LLM", "weight heredity without memory"), ("E-LLM", "E-LLM-free", "admissibility constraint"),
                      ("E-LLM", "ES-56+", "C3' vs CMA-ES, all seeds (addition)")]:
        if a in mats and b in mats:
            d = boot_diff(mats[a], mats[b], None, seed=1)
            lines.append(f"| {tag}: {a} − {b} | {d[0]:+.4f} | [{d[1]:+.4f}, {d[2]:+.4f}] |")
            summary[f"contrast {a}-{b}"] = d
    lines += ["", "### Same contrasts restricted to units that pass the test constraints (sensitivity analysis)", "",
              "| Contrast | units (A, B) | Δ acc | 95% CI |", "|---|---|---|---|"]
    for a, b in [("E-LLM", "R-LLM"), ("E-LLM", "E-RAND"), ("E-LLM", "ES-56"), ("E-LLM", "ES-56+"), ("E-LLM", "E-LLM-nohist"), ("E-LLM", "E-LLM-free")]:
        if a in pass_mats and b in pass_mats:
            d = boot_diff(pass_mats[a], pass_mats[b], None, seed=2)
            lines.append(f"| {a} − {b} | {len(pass_mats[a])}, {len(pass_mats[b])} | {d[0]:+.4f} | [{d[1]:+.4f}, {d[2]:+.4f}] |")
            summary[f"pass-only contrast {a}-{b}"] = d
    lines.append("")
    # ---- cost table
    lines += ["## Cost per unit", "", "Evaluations = dev evaluations of candidate models used for selection.", "",
              "| Arm | Units | Dev evaluations per unit | Editor $ per unit | Wall-clock min per unit (selection loop) |", "|---|---|---|---|---|"]
    for arm in ["E-LLM", "R-LLM", "E-LLM-nohist", "E-LLM-free", "E-RAND"]:
        logs = load_logs(arm)
        if not logs:
            continue
        ev = np.mean([sum(g["n_valid"] for g in l["generations"][:10]) for l in logs.values()])
        usd = np.mean([sum((g["meta"].get("cost_usd") or 0) for g in l["generations"][:10]) for l in logs.values()])
        secs = [sum(g.get("seconds") or 0 for g in l["generations"][:10]) for l in logs.values()]
        lines.append(f"| {arm} | {len(logs)} | {ev:.0f} | ${usd:.3f} | {np.mean(secs) / 60:.1f} |" if any(secs) else
                     f"| {arm} | {len(logs)} | {ev:.0f} | ${usd:.3f} | n/a |")
    for arm in ("ES-56", "ES-56+"):
        L = es_logs(arm == "ES-56+")
        if L and unit_tests(arm):
            lines.append(f"| {arm} | {len(L)} | 60 (300 also tested) | $0.000 | n/a |")
    lines.append("")
    # ---- generation trajectories
    lines += ["## Generational trajectories", ""]
    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
        plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
                             "axes.edgecolor": "#888", "axes.grid": True, "grid.color": "#e6e6e6"})
        fig, ax = plt.subplots(figsize=(7, 4.2))
        for arm in ["E-LLM", "E-LLM-nohist", "E-LLM-free", "E-RAND"]:
            logs = load_logs(arm)
            if not logs:
                continue
            curves = []
            for log in logs.values():
                c = [log["generations"][0]["parent_fitness"]] + [g["parent_fitness"] for g in log["generations"][1:]]
                last = log["generations"][-1]
                acc = [o for o in last["offspring"] if o["k"] == last["accepted"]]
                c.append(acc[0]["ev"]["fitness"] if acc else last["parent_fitness"])
                c = c[:11]
                curves.append(c); ax.plot(range(len(c)), c, color=COLORS[arm], alpha=0.18, lw=1)
            L = min(len(c) for c in curves); m = np.mean([c[:L] for c in curves], 0)
            ax.plot(range(L), m, color=COLORS[arm], lw=2, label=f"{arm} (n={len(curves)})")
            ax.annotate(arm, (L - 1, m[-1]), xytext=(4, 0), textcoords="offset points", color="#333", fontsize=8, va="center")
        rl = load_logs("R-LLM")
        if rl:
            best = np.mean([l["best_seen"]["fitness"] for l in rl.values() if l.get("best_seen")])
            ax.axhline(best, color=COLORS["R-LLM"], lw=2, ls="--", label="R-LLM best-of-60 (no heredity)")
        ax.set_xlabel("generation"); ax.set_ylabel("dev target fitness (mean log p correct)")
        ax.set_title("Dev fitness across generations (thin: lineages, thick: mean)", fontsize=10, loc="left")
        ax.legend(frameon=False, fontsize=8, loc="lower right"); fig.tight_layout(); fig.savefig(FIG / "dev_fitness.png", dpi=160)
        plt.close(fig)
        # test accuracy vs generation for E-LLM
        logs = load_logs("E-LLM")
        if logs and orig:
            fig, ax = plt.subplots(figsize=(7, 4.2))
            gens = ["0", "1", "2", "3", "5", "7", "10"]
            allc = []
            for log in logs.values():
                xs, ys = [], []
                for g in gens:
                    t = orig if g == "0" else log["tests"].get(g)
                    if t:
                        xs.append(int(g)); ys.append(t["target_acc"])
                ax.plot(xs, ys, color=COLORS["E-LLM"], alpha=0.25, lw=1, marker="o", ms=3); allc.append(dict(zip(xs, ys)))
            mx = [int(g) for g in gens if all(int(g) in c for c in allc)]
            ax.plot(mx, [np.mean([c[x] for c in allc]) for x in mx], color=COLORS["E-LLM"], lw=2, marker="o", ms=8, label="E-LLM mean")
            for arm in ["E-LLM-nohist", "E-LLM-free", "E-RAND"]:
                lg = load_logs(arm)
                pts = {g: [l["tests"][g]["target_acc"] for l in lg.values() if g in l["tests"]] for g in ("5", "10")}
                xs = [int(g) for g in pts if pts[g]]
                if xs:
                    ax.plot([0] + xs, [orig["target_acc"]] + [np.mean(pts[str(x)]) for x in xs], color=COLORS[arm], lw=2, marker="o", ms=8, label=f"{arm} mean")
            ax.axhline(orig["target_acc"], color="#777", lw=1, ls=":", label="original")
            ax.set_xlabel("generation"); ax.set_ylabel("held-out TEST target accuracy")
            ax.set_title("Held-out accuracy across generations", fontsize=10, loc="left")
            ax.legend(frameon=False, fontsize=8); fig.tight_layout(); fig.savefig(FIG / "test_accuracy.png", dpi=160); plt.close(fig)
        # protected drift: constrained vs free
        fig, ax = plt.subplots(figsize=(7, 4.2)); drew = False
        for arm in ["E-LLM", "E-LLM-free"]:
            logs = load_logs(arm)
            if not logs:
                continue
            cs = [[g["parent"]["protected"] for g in l["generations"]] for l in logs.values()]
            for c in cs:
                ax.plot(range(1, len(c) + 1), c, color=COLORS[arm], alpha=0.25, lw=1)
            L = min(map(len, cs)); ax.plot(range(1, L + 1), np.mean([c[:L] for c in cs], 0), color=COLORS[arm], lw=2, label=arm); drew = True
        if drew:
            ax.set_xlabel("generation (parent)"); ax.set_ylabel("protected dev fitness")
            ax.set_title("Protected abilities under constrained vs unconstrained selection", fontsize=10, loc="left")
            ax.legend(frameon=False, fontsize=8); fig.tight_layout(); fig.savefig(FIG / "protected_drift.png", dpi=160)
        plt.close(fig)
        # per-lineage strip plot
        fig, ax = plt.subplots(figsize=(7, 3.8))
        for i, arm in enumerate([a for a in ARMS if a in summary]):
            ys = summary[arm]["per_lineage"]
            xs = i + np.linspace(-0.15, 0.15, len(ys)) if len(ys) > 1 else [i]
            ax.scatter(xs, ys, s=40, color=COLORS[arm], edgecolor="white", lw=1.5, zorder=3)
            ax.plot([i - 0.25, i + 0.25], [np.mean(ys)] * 2, color="#333", lw=2)
        if orig:
            ax.axhline(orig["target_acc"], color="#777", lw=1, ls=":")
        ax.set_xticks(range(len([a for a in ARMS if a in summary]))); ax.set_xticklabels([a for a in ARMS if a in summary], fontsize=8)
        ax.set_ylabel("held-out TEST target accuracy"); ax.set_title("Final accuracy per lineage (bar = arm mean; dotted = original)", fontsize=10, loc="left")
        fig.tight_layout(); fig.savefig(FIG / "final_by_arm.png", dpi=160); plt.close(fig)
        lines += ["![dev fitness](figures/dev_fitness.png)", "", "![test accuracy](figures/test_accuracy.png)", "",
                  "![protected drift](figures/protected_drift.png)", "", "![final by arm](figures/final_by_arm.png)", ""]
    except ImportError:
        pass
    # ---- E-LLM trajectory table
    logs = load_logs("E-LLM")
    if logs and orig:
        lines += ["### E-LLM held-out target accuracy by generation", "", "| Lineage | g0 | g1 | g2 | g3 | g5 | g7 | g10 | accepted | genome ops |", "|---|---|---|---|---|---|---|---|---|---|"]
        for n, l in logs.items():
            cells = [f"{orig['target_acc']:.3f}"] + [f"{l['tests'][g]['target_acc']:.3f}" if g in l["tests"] else "–" for g in ("1", "2", "3", "5", "7", "10")]
            acc = sum(g["accepted"] is not None for g in l["generations"])
            lines.append(f"| {n} | " + " | ".join(cells) + f" | {acc}/{len(l['generations'])} | {l['generations'][-1].get('genome_len', '')} |")
        lines.append("")
    # ---- operator statistics
    lines += ["## Mutation-operator statistics", "", "| Arm | Generations | Valid offspring | Improving | Admissible & improving | Accepted gens | Editor cost |", "|---|---|---|---|---|---|---|"]
    for arm in ["E-LLM", "R-LLM", "E-LLM-nohist", "E-LLM-free", "E-RAND"]:
        logs = load_logs(arm)
        if not logs:
            continue
        G = [g for l in logs.values() for g in l["generations"]]
        cost = sum((g["meta"].get("cost_usd") or 0) for g in G)
        lines.append(f"| {arm} | {len(G)} | {sum(g['n_valid'] for g in G)}/{6 * len(G)} | {sum(g['n_improving'] for g in G)} | "
                     f"{sum(g['n_admissible_improving'] for g in G)} | {sum(g['accepted'] is not None for g in G)} | ${cost:.2f} |")
        summary.setdefault(arm, {})["operator"] = dict(gens=len(G), valid=sum(g['n_valid'] for g in G), improving=sum(g['n_improving'] for g in G),
                                                       adm_improving=sum(g['n_admissible_improving'] for g in G), cost=cost)
    lines.append("")
    # ---- DFE
    dfe = R / "dfe.json"
    if dfe.exists():
        D = json.loads(dfe.read_text())
        lines += ["## Distribution of fitness effects of random mutations (evolvability)", "",
                  "| Checkpoint | genome len | beneficial | admissible-beneficial | median Δfit | mean deleterious Δfit |", "|---|---|---|---|---|---|"]
        agg = {}
        for k, v in sorted(D.items()):
            ok = [e for e in v["effects"] if "dfit" in e]
            if not ok:
                continue
            fr = np.mean([e["dfit"] > 0 for e in ok]); fa = np.mean([e["dfit"] > 0 and e["admissible"] for e in ok])
            dl = [e["dfit"] for e in ok if e["dfit"] < 0]
            lines.append(f"| {k} | {v['genome_len']} | {fr:.2f} | {fa:.2f} | {np.median([e['dfit'] for e in ok]):+.4f} | {np.mean(dl) if dl else 0:+.4f} |")
            g = k.split("/")[-1]; arm = k.split("/")[0]
            agg.setdefault((arm, g), []).append((fr, fa))
        lines += ["", "Mean over lineages: " + "; ".join(f"{a} {g}: beneficial {np.mean([x[0] for x in v]):.2f}, admissible-beneficial {np.mean([x[1] for x in v]):.2f}"
                                                   for (a, g), v in sorted(agg.items())), ""]
    # ---- crossover
    cx = R / "crossover.json"
    if cx.exists() and orig:
        C = json.loads(cx.read_text()); o = orig["target_acc"]
        single = {k.split("/")[1]: v["test"]["target_acc"] for k, v in C.items() if k.startswith("single/")}
        inter = []
        lines += ["## Genetics: additivity, crossover, merging", ""]
        for k, v in C.items():
            if k.startswith("union/"):
                A, B = k.split("/")[1].split("+")
                inter.append(v["test"]["target_acc"] - o - (single[A] - o) - (single[B] - o))
        if inter:
            lines.append(f"Union interaction term Δ(A∪B) − Δ(A) − Δ(B) on test accuracy over {len(inter)} ordered pairs: "
                         f"mean {np.mean(inter):+.4f}, range [{min(inter):+.4f}, {max(inter):+.4f}] "
                         f"(negative = sub-additive / antagonistic epistasis).")
            best_single = {k: v for k, v in single.items()}
            better = sum(1 for k, v in C.items() if k.startswith("union/") and v["test"]["target_acc"] > max(single[x] for x in k.split("/")[1].split("+")))
            lines.append(f"Unions beating both parents: {better}/{len(inter)}.")
        ties = [v["test"]["target_acc"] for k, v in C.items() if k.startswith("ties/")]
        if ties:
            lines.append(f"TIES merges: mean test acc {np.mean(ties):.4f} (n={len(ties)}).")
        for kind in ("llm", "random"):
            bs = [(k, v["best"]) for k, v in C.items() if k.startswith(f"cross_{kind}/")]
            if bs:
                accs = [b["test"]["target_acc"] for _, b in bs if b]
                lines.append(f"{kind.upper()} crossover (best admissible of 6 recombinants per pair): test acc " +
                             ", ".join(f"{k.split('/')[1]}={b['test']['target_acc']:.3f}" if b else f"{k.split('/')[1]}=none" for k, b in bs) +
                             (f"; mean {np.mean(accs):.4f}" if accs else ""))
        lines.append("")
    led = json.loads((R / "ledger.json").read_text())
    spent = sum(e["charged_or_reserved_usd"] for e in led["entries"])
    lines += [f"Editor spend committed in ledger: **${spent:.2f}** of the $20.00 hard cap ({len(led['entries'])} calls).", ""]
    summary["spend_usd"] = spent
    (R / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    (R / "summary.json").write_text(json.dumps(summary, indent=1, default=float))
    print("\n".join(lines[:60]))


if __name__ == "__main__":
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    main()
